-- 閉店のお知らせ文 (2026-11-25, 紗代さんの要望)
-- 例: 「飯田駅で営業していた店舗は閉店しました。現在も駒ヶ根市で営業を続けています。」(移転ではない閉店)
-- 空 (NULL) なら記事ページは決まり文「こちらは閉店されています。記事は掲載当時の内容です。」を出す。
-- 閉店のときだけ保存する (通常・移転に戻すと消す)。カードの「閉店されています」と白黒表示は変わらない。
ALTER TABLE posts ADD COLUMN IF NOT EXISTS closure_note text;

COMMENT ON COLUMN posts.closure_note IS
  '閉店のお知らせ文。閉店のときだけ記事ページの写真の帯に出す。空なら決まり文';
